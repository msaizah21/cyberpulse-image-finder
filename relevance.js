/**
 * CyberPulse Editorial Relevance — deterministic, offline, metadata-only estimate.
 * It does NOT inspect pixels and is NOT a machine-learning probability.
 * Browser and Node test compatible.
 */
(function (root) {
  'use strict';
  const stop=new Set('a an and are as at by close concept conceptual computer cyber cybersecurity data digital for from high image images in is it landscape latest modern of on or photo photography picture professional security stock technology the to up using via with new news abstract background view macro dark'.split(' '));
  const aliases={
    chips:'chip',chipset:'chip',chipsets:'chip',semiconductor:'chip',semiconductors:'chip',microchip:'chip',microchips:'chip',processor:'chip',processors:'chip',cpu:'chip',gpu:'chip',gpus:'chip',graphics:'chip',circuit:'chip',motherboard:'chip',
    servers:'server',datacenter:'server',datacenters:'server',centre:'center',centres:'center',cloud:'server',racks:'rack',
    hospitals:'hospital',healthcare:'hospital',clinics:'hospital',medical:'hospital',patients:'hospital',
    phones:'phone',smartphone:'phone',smartphones:'phone',android:'phone',mobile:'phone',
    emails:'email',inbox:'email',phishing:'email',messages:'email',
    laptops:'laptop',computers:'computer',workstations:'computer',
    banking:'bank',banks:'bank',financial:'bank',finance:'bank',payments:'bank',
    networks:'network',networking:'network',firewalls:'firewall',hacking:'hacker',hackers:'hacker',
    passwords:'password',credentials:'password',ransom:'ransomware',encryption:'encrypt',encrypted:'encrypt',
    breaches:'breach',leak:'breach',leaks:'breach',leaked:'breach',
    codes:'code',coding:'code',programming:'code',screens:'screen',monitors:'screen',
    ai:'ai',artificial:'ai',intelligence:'ai',learning:'ai',robotics:'ai',
    offices:'office',buildings:'building',analysts:'analyst',teams:'team',
    investigations:'investigation',threats:'threat',attacks:'attack',attackers:'attack',
  };
  const blocked=/\b(icon|illustration|vector|cartoon|drawing|poster|infographic|diagram|mockup|template|wallpaper|screenshot|screengrab|watermark|3d render|generated by ai)\b/i;
  function tokens(value){
    return [...new Set(String(value||'').toLowerCase().replace(/data[ -]?cent(?:er|re)s?/g,' datacenter ').match(/[a-z0-9]+/g)||[])].map(w=>aliases[w]||w).filter(w=>w.length>=3||w==='ai').filter(w=>!stop.has(w));
  }
  function uniqueTerms(value){return [...new Set(tokens(value))];}
  const clamp=(v,min,max)=>Math.max(min,Math.min(max,v));
  function estimate(item,query,article){
    const metadata=`${item.title||''} ${item.tags||''} ${item.description||''}`;
    const imageTerms=new Set(uniqueTerms(metadata));
    const q=uniqueTerms(query).slice(0,12);
    const context=uniqueTerms([article?.topic||'',...(article?.visualConcepts||[]).slice(0,4),...(article?.stockSearches||[]).slice(0,2),...(article?.matchedKeywords||[])].join(' ')).slice(0,20);
    const found=q.filter(w=>imageTerms.has(w));
    const contextual=context.filter(w=>imageTerms.has(w));
    const queryRatio=q.length?found.length/q.length:0;
    const contextRatio=context.length?contextual.length/context.length:0;
    const directPhrase=String(metadata).toLowerCase().includes(String(query||'').toLowerCase()) && String(query||'').length>=9;
    let topic=Math.round(7+50*queryRatio+12*contextRatio+(directPhrase?4:0));
    topic=clamp(topic,0,70);
    if(!found.length)topic=Math.min(topic,18);
    let quality=0;
    const width=Number(item.width)||0;
    const height=Number(item.height)||0;
    if(width>=3000)quality=20;
    else if(width>=2200)quality=18;
    else if(width>=1600)quality=15;
    else if(width>=1200)quality=11;
    else if(width>=900)quality=7;
    else quality=3;
    const ratio=height?width/height:0;
    let banner=0;
    if(ratio>=1.45&&ratio<=1.95)banner=10;
    else if(ratio>=1.30&&ratio<=2.30)banner=8;
    else if(ratio>=1.32)banner=5;
    else if(!ratio)banner=2;
    const graphic=blocked.test(metadata)||/svg\b/i.test(item.mime||'')||item.kind==='illustration';
    const score=clamp(topic+quality+banner-(graphic?35:0),0,99);
    const matchedTerms=[...new Set([...found,...contextual])].slice(0,4);
    return {score,topic,quality,banner,matchedTerms,graphic,
      tier:score>=78?'Strong estimated match':score>=60?'Good estimated match':score>=40?'Possible match':'Needs editorial review',
      reason:matchedTerms.length?`Matches photo description: ${matchedTerms.join(', ')}`:'Few direct topic words in the photo description'};
  }
  root.CyberPulseRelevance={estimate,tokens,blocked};
})(typeof window!=='undefined'?window:globalThis);
